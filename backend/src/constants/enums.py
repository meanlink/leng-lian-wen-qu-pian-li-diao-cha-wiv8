from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class SensitivityStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    blocked = 'blocked'
    switched = 'switched'
class TierStatus(str, Enum):
    pending = 'pending'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
